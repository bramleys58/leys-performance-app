"""Turn data/master_library.xlsx into supabase/seed/exercises.sql.

Run again whenever the library file changes:
    python3 tools/build_exercise_seed.py
The SQL only adds exercises that are not in the database yet (matched on name),
so it is safe to run more than once.
"""
import pathlib
import openpyxl

ROOT = pathlib.Path(__file__).resolve().parent.parent
TRACK = {
    "Load": "load", "Bodyweight reps": "bodyweight_reps", "Time": "time", "Distance": "distance",
    "Distance/height": "distance_height", "Reps only": "reps_only", "Completion": "completion",
}


def q(v):
    if v is None or str(v).strip() == "":
        return "null"
    return "'" + str(v).strip().replace("'", "''") + "'"


def step(equipment):
    e = (equipment or "").lower()
    if "dumbbell" in e or "kettlebell" in e or "kb" in e:
        return 2
    return 2.5


ws = openpyxl.load_workbook(ROOT / "data" / "master_library.xlsx", data_only=True)["Master Library"]
head = [c.value for c in ws[1]]
col = {h: i for i, h in enumerate(head)}
rows, seen = [], set()
for r in ws.iter_rows(min_row=2, values_only=True):
    name = (r[col["Exercise Name"]] or "").strip()
    if not name or name.lower() in seen:
        continue
    seen.add(name.lower())
    aliases = [a.strip() for a in str(r[col["Aliases"]] or "").split(";") if a.strip()]
    alias_sql = "array[" + ", ".join(q(a) for a in aliases) + "]::text[]"
    check = str(r[col["Check"]] or "").strip()
    sets = r[col["Sets"]]
    rows.append(
        "(" + ", ".join([
            q(name), alias_sql, q(r[col["Movement Pattern"]]), q(r[col["Primary Muscle"]]), q(r[col["Equipment"]]),
            "'" + TRACK.get(r[col["Tracking Type"]], "load") + "'", str(step(r[col["Equipment"]])),
            str(int(sets)) if isinstance(sets, (int, float)) else "null",
            q(r[col["Reps"]]), q(r[col["Tempo"]]), q(r[col["Coaching Note"]]), q(r[col["Video Link"]]), q(r[col["Alt Video"]]),
            "true" if check and check != "No demo video yet" else "false",
        ]) + ")"
    )

sql = (
    "-- Generated by tools/build_exercise_seed.py from data/master_library.xlsx. Do not edit by hand.\n"
    "insert into public.exercises\n"
    "  (name, aliases, movement_pattern, primary_muscle, equipment, tracking_type, weight_step,\n"
    "   default_sets, default_reps, default_tempo, default_note, video_url, alt_video_url, needs_review)\nvalues\n"
    + ",\n".join(rows)
    + "\non conflict (lower(name)) do nothing;\n"
)
(ROOT / "supabase" / "seed" / "exercises.sql").write_text(sql, encoding="utf-8")
print(len(rows), "exercises written")
